// Folds every models/<stem>.json sidecar with what the build measures off
// models/<stem>.glb into models/catalog.json and src/meshCatalog.ts
// (docs/design/mesh-catalog.md, nav-wright#147). Measured, never typed:
// proportions from the mesh's bounds, frame from its glb extras or bounds,
// lights from the same station profile anchorLights seats them on in the
// 3D view. A sidecar that fails the schema, or a mesh without one, stops
// the build.
//
//   npm run build && node scripts/mesh-catalog.mjs
//
// Deterministic for the same meshes and sidecars.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { format, resolveConfig } from 'prettier';
import { z } from 'zod';
import { LIGHT_Z_TO_X, anchorLights } from '../dist/modelTransform.js';
import { meshRecordSchema, meshSidecarSchema } from '../dist/meshRecord.js';
import { modelFrame, profileHullModel } from '../dist/sceneProfile.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MODELS = join(ROOT, 'models');

// three's texture path reaches for browser globals under Node; the
// catalog is geometry only.
globalThis.self ??= globalThis;
globalThis.createImageBitmap ??= async () => ({ width: 1, height: 1, close() {} });

function loadScene(file) {
  const buf = readFileSync(file);
  const ab = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
  return new Promise((resolve, reject) =>
    new GLTFLoader().parse(ab, '', (g) => resolve(g.scene), reject),
  );
}

const r3 = (x) => Math.round(x * 1000) / 1000;

/** The light seats anchorLights gives a masthead light, a sidelight and a
 * stern light on this mesh, in the hull's own [fx, z] frame: the mesh is
 * placed as a vessel of length 2, so world x is fx and world y is z scaled
 * by LIGHT_Z_TO_X. Sentinel stations tell anchorLights which light is
 * which; the aft mast is unused. */
const MAST = 9;
const STERN = -1;
function measure(scene) {
  const raw = new THREE.Box3().setFromObject(scene);
  const named = modelFrame(scene);
  const frame = {
    waterlineZ: named.waterlineZ ?? raw.min.z,
    hullX: named.hullX ?? [raw.min.x, raw.max.x],
  };
  const length = frame.hullX[1] - frame.hullX[0];
  const proportions = {
    lengthBeam: r3(length / (raw.max.y - raw.min.y)),
    lengthHeight: r3(length / (raw.max.z - frame.waterlineZ)),
  };
  const profile = profileHullModel(scene, 2, { sternX: -1, bowX: 1 });
  if (!profile) throw new Error('nothing to profile');
  const hull = { beam: 1, mastX: MAST, aftMastX: NaN, sternX: STERN, bowX: 1 };
  const [masthead, sidelight, stern] = anchorLights(
    [
      { fx: MAST, py: 0, z: 0 },
      { fx: 0.5, py: 1, z: 0 },
      { fx: STERN, py: 0, z: 0 },
    ],
    2,
    hull,
    profile,
  ).map(([x, y]) => [r3(x), r3(y / LIGHT_Z_TO_X)]);
  return {
    proportions,
    frame: { waterlineZ: r3(frame.waterlineZ), hullX: frame.hullX.map(r3) },
    lights: { masthead, sidelight, stern },
  };
}

const glbs = readdirSync(MODELS)
  .filter((f) => f.endsWith('.glb'))
  .sort();
const sidecars = new Set(readdirSync(MODELS).filter((f) => f.endsWith('.json')));
const records = [];
for (const glb of glbs) {
  const stem = glb.slice(0, -4);
  if (!sidecars.delete(`${stem}.json`)) throw new Error(`models/${glb} has no sidecar`);
  const sidecar = meshSidecarSchema.parse(
    JSON.parse(readFileSync(join(MODELS, `${stem}.json`), 'utf8')),
  );
  if (sidecar.file !== glb) throw new Error(`models/${stem}.json names ${sidecar.file}`);
  const record = meshRecordSchema.parse({
    ...sidecar,
    ...measure(await loadScene(join(MODELS, glb))),
  });
  records.push(record);
  console.log(
    `${glb.padEnd(36)} L/B ${String(record.proportions.lengthBeam).padStart(6)}  L/H ${String(record.proportions.lengthHeight).padStart(6)}  masthead ${record.lights.masthead}  side ${record.lights.sidelight}  stern ${record.lights.stern}`,
  );
}
for (const orphan of sidecars)
  if (orphan !== 'catalog.json' && orphan !== 'mesh-record.schema.json')
    throw new Error(`models/${orphan} has no mesh`);

writeFileSync(join(MODELS, 'catalog.json'), JSON.stringify(records, null, 2) + '\n');
writeFileSync(
  join(MODELS, 'mesh-record.schema.json'),
  JSON.stringify(z.toJSONSchema(meshRecordSchema), null, 2) + '\n',
);
writeFileSync(
  join(ROOT, 'src', 'meshCatalog.ts'),
  await format(
    `// Generated by scripts/mesh-catalog.mjs — do not edit.
// One record per mesh under models/, the sidecar's authored fields and the
// build's measurements (docs/design/mesh-catalog.md). models/catalog.json
// is the same data as JSON.
import type { MeshRecord } from './meshRecord.js';

export const meshCatalog: readonly MeshRecord[] = ${JSON.stringify(records, null, 2)};
`,
    { ...(await resolveConfig(ROOT)), filepath: join(ROOT, 'src', 'meshCatalog.ts') },
  ),
);
console.log(`${records.length} records`);
